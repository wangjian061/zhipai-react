export function validSupportEmail(email) {
  return (
    typeof email === "string" &&
    /^[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+$/.test(
      email,
    )
  );
}
